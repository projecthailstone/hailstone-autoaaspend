local settings = require('lib.settings')

case("settings: defaults and repair of junk", function()
  local d = settings.defaults()
  eq(d.order, "skip")
  eq(#d.list, 0)
  eq(d.prereqs, true)
  eq(d.combat, false)
  local r = settings.repair({ order = "bogus", reserve = -5, list = { { name = "A", cap = "3" }, { name = "" }, 7,
    { name = "a" }, { name = "B", on = false, group = 12 } }, fill = { on = true, tabs = { class = true }, max_cost = 9e9 } })
  eq(r.order, "skip")
  eq(r.reserve, 0)
  eq(#r.list, 2, "empty, non-table and duplicate (any case) entries dropped")
  eq(r.list[1].cap, 3)
  eq(r.list[2].on, false)
  eq(r.list[2].group, 12)
  eq(r.fill.on, true)
  eq(r.fill.tabs.class, true)
  eq(r.fill.tabs.general, true, "a tab not given keeps its default")
  eq(r.fill.max_cost, 1000)
  eq(settings.repair(nil).order, "skip")
end)

case("settings: add, find, move, remove", function()
  local S = settings.defaults()
  settings.add(S, "Innate Strength", 10)
  settings.add(S, "Mystical Shielding", 20)
  settings.add(S, "Combat Agility", 30)
  eq(#S.list, 3)
  settings.add(S, "innate strength", 10)
  eq(#S.list, 3, "already listed")
  local e, i = settings.find(S, nil, 20)
  eq(e.name, "Mystical Shielding")
  eq(i, 2)
  check(settings.find(S, "COMBAT AGILITY") ~= nil, "found by name, ignoring case")
  settings.move(S, "Combat Agility", 30, 1)
  eq(S.list[1].name, "Combat Agility")
  settings.move(S, "Combat Agility", 30, 99)
  eq(S.list[3].name, "Combat Agility", "clamped to the end")
  check(settings.remove(S, "Innate Strength", 10))
  check(not settings.remove(S, "Innate Strength", 10))
  eq(#S.list, 2)
  -- an entry added by name only learns its group later
  settings.add(S, "Run Speed")
  eq(S.list[3].group, 0)
  settings.add(S, "Run Speed", 77)
  eq(S.list[3].group, 77)
end)

case("settings: set by path", function()
  local S = settings.defaults()
  local ok
  S, ok = settings.set(S, "reserve", 25)
  check(ok)
  eq(S.reserve, 25)
  S, ok = settings.set(S, "fill.tabs.class", true)
  check(ok)
  eq(S.fill.tabs.class, true)
  S, ok = settings.set(S, "list", {})
  check(not ok, "the list is changed by its own commands")
  S, ok = settings.set(S, "order", "wait")
  eq(S.order, "wait")
end)
